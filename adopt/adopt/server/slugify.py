"""A faithful Python port of `gosimple/slug`.`Make`, as pinned in `api/go.mod`.

WHY THIS EXISTS
---------------
Studies were, until now, only creatable through the Go dashboard API
(`api/internal/server/handler/studies/create.go`), which derives the study's
slug with `slug.Make(name)` from `github.com/gosimple/slug v1.12.0`
(`api/internal/storage/study.go`). The slug *is* the study's URL and its
lookup key in every conf endpoint, so a Python re-implementation that disagreed
with Go — even in one character — would hand out a different URL for the same
name depending on which door the study came in through, and there is no way to
fix that after the fact without breaking links.

So this is a port, not an approximation. It reproduces `slug.MakeLang(s, "en")`
step for step:

1. `strings.TrimSpace`
2. custom substitutions — **not applicable**: nothing in `api/` ever assigns
   `slug.CustomSub` / `slug.CustomRuneSub`, so both maps are nil there.
3. the "en" rune substitutions — `enSub` *plus* `defaultSub`, which
   `languages_substitution.go`'s `init()` merges into every language map
4. `unidecode.Unidecode` (`github.com/gosimple/unidecode v1.0.1`)
5. lowercase (`slug.Lowercase` defaults to true and `api/` never changes it)
6. `[^a-zA-Z0-9-_]` -> "-"
7. `-+` -> "-"
8. trim "-" and "_" from both ends
9. `slug.MaxLength` truncation — **not applicable**: it defaults to 0 (off) and
   `api/` never sets it.

KNOWN DEVIATIONS
----------------
* `str.strip()` is used for step 1 where Go uses `strings.TrimSpace`
  (`unicode.IsSpace`). The two disagree on a handful of codepoints — Python
  counts U+001C..U+001F as whitespace, Go does not. The difference is
  unobservable here: every codepoint either language calls whitespace
  transliterates to whitespace or to nothing, so it becomes a dash in step 6
  and is removed by the trim in step 8 regardless. `test_slugify.py` asserts
  this against recorded Go output for every BMP codepoint in leading, trailing
  and interior position.
* Lone surrogates (U+D800..U+DFFF) are not covered by the table. They cannot
  survive JSON decoding, so no request body can contain one.
* Codepoints above the BMP (U+10000 and up) are dropped, which is what
  `unidecode.Unidecode` does — its table is `[65536][]rune` and anything
  `>= transCount` is skipped. Emoji therefore contribute nothing at all, not
  even a dash.

REGENERATING THE TABLE
----------------------
`_TRANSLITERATIONS_B85` is `zlib`-compressed, base85-encoded, "\\x00"-joined
transliterations for U+0080..U+FFFF in codepoint order, taken directly from
the Go library rather than from any Python transliteration package (there is
none in `adopt`'s dependencies, and no two of them agree anyway). To rebuild
it, run this against `github.com/gosimple/unidecode v1.0.1`:

    for c := 0x80; c < 0x10000; c++ {
        if c >= 0xD800 && c <= 0xDFFF {
            emit("")  // surrogate: not a standalone rune, but keep the slot
            continue
        }
        emit(unidecode.Unidecode(string(rune(c))))
    }

then join with "\\x00", `zlib.compress(blob, 9)`, `base64.b85encode`. Every
codepoint gets a slot, including the surrogates, so the array can be indexed
by `codepoint - 0x80` with no arithmetic.
"""

import base64
import re
import zlib
from typing import List, Optional

# github.com/gosimple/slug@v1.12.0 languages_substitution.go: enSub with
# defaultSub merged into it by that file's init(). Easy to miss — enSub's own
# literal is only "&" and "@" — but the quote entries matter a lot in practice:
# they are *deletions*, so "Nandan's study" slugs to "nandans-study", not
# "nandan-s-study". Applied to the *original* string, before transliteration,
# which is why "R&D" slugs to "randd" and not "r-d".
_EN_SUB = {
    "&": "and",
    "@": "at",
    # --- defaultSub ---
    '"': "",
    "'": "",
    "’": "",  # right single quotation mark
    "‒": "-",  # figure dash
    "–": "-",  # en dash
    "—": "-",  # em dash
    "―": "-",  # horizontal bar
}

# Go source: regexp.MustCompile("[^a-zA-Z0-9-_]"). The bare "-" between "9" and
# "_" is a literal in RE2, not the start of a range — verified against real Go
# output (":" is 0x3A, inside a hypothetical "9-_" range, and Go dashes it).
_NON_AUTHORIZED_CHARS = re.compile(r"[^a-zA-Z0-9\-_]")
_MULTIPLE_DASHES = re.compile(r"-+")

_MAX_ASCII = 0x7F
_TABLE_START = 0x80
_TABLE_END = 0x10000  # unidecode's table is [65536][]rune; above this: dropped

_transliterations: Optional[List[str]] = None


def _table() -> List[str]:
    """Decode the transliteration table on first use.

    Mirrors `unidecode`'s own lazy `decodingOnce` decode of a zlib blob. Costs
    ~200KB of resident memory once a study is created; not worth doing at
    import time in a process that may never slug anything.
    """
    global _transliterations
    if _transliterations is None:
        blob = zlib.decompress(base64.b85decode(_TRANSLITERATIONS_B85))
        _transliterations = blob.decode("utf8").split("\x00")
        # 0x80..0xFFFF inclusive
        assert len(_transliterations) == _TABLE_END - _TABLE_START
    return _transliterations


def _unidecode(s: str) -> str:
    """Port of `unidecode.Unidecode` (gosimple/unidecode v1.0.1)."""
    table = _table()
    out = []
    for ch in s:
        c = ord(ch)
        if c <= _MAX_ASCII:
            out.append(ch)
            continue
        if c >= _TABLE_END:
            # "Ignore reserved chars" — anything outside the BMP is dropped
            continue
        out.append(table[c - _TABLE_START])
    return "".join(out)


def slugify(name: str) -> str:
    """Port of `slug.Make(name)` — i.e. `slug.MakeLang(name, "en")`.

    Returns the same string the Go dashboard API would store for `name`. May
    return "" (e.g. for a name made only of emoji); callers decide whether an
    empty slug is acceptable, exactly as the Go handler does — which is to say
    it does not check either.
    """
    s = name.strip()

    # SubstituteRune(slug, enSub): one pass, rune by rune.
    s = "".join(_EN_SUB.get(ch, ch) for ch in s)

    s = _unidecode(s)

    # slug.Lowercase defaults to true. The string is pure ASCII by now, so
    # str.lower() and strings.ToLower() cannot diverge.
    s = s.lower()

    s = _NON_AUTHORIZED_CHARS.sub("-", s)
    s = _MULTIPLE_DASHES.sub("-", s)
    return s.strip("-_")


